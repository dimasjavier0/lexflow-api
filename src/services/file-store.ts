import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DeleteObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";

/**
 * Where images and audio live. In production `MEDIA_BUCKET` names an S3 bucket that CloudFront
 * serves at /uploads/*; without it (local development) they go to the uploads/ folder, which
 * the API serves itself. Either way a file's URL is `<public base>/uploads/<filename>`.
 */
const bucket = process.env.MEDIA_BUCKET || null;
const KEY_PREFIX = "uploads/";

export const localUploadDirectory = fileURLToPath(new URL("../../uploads", import.meta.url));
/** Whether the API itself must serve /uploads (only without a bucket). */
export const servesUploadsLocally = bucket === null;

let s3: S3Client | null = null;
function s3Client(): S3Client {
  s3 ??= new S3Client({});
  return s3;
}

/** Filenames are generated by the API; anything else could escape the folder or the prefix. */
function safeFilename(filename: string): string {
  const name = path.basename(filename);
  if (!name || name !== filename) throw new Error(`Invalid upload filename: ${filename}`);
  return name;
}

export function uploadUrl(baseUrl: string, filename: string): string {
  return `${baseUrl}/uploads/${filename}`;
}

export async function saveUpload(filename: string, data: Buffer, contentType: string): Promise<void> {
  const name = safeFilename(filename);
  if (bucket) {
    // Names are unique per upload, so browsers and CloudFront may keep them forever.
    await s3Client().send(new PutObjectCommand({ Bucket: bucket, Key: KEY_PREFIX + name, Body: data, ContentType: contentType, CacheControl: "public, max-age=31536000, immutable" }));
    return;
  }
  await fs.mkdir(localUploadDirectory, { recursive: true });
  await fs.writeFile(path.join(localUploadDirectory, name), data);
}

export async function deleteUpload(filename: string): Promise<void> {
  const name = safeFilename(filename);
  if (bucket) {
    await s3Client().send(new DeleteObjectCommand({ Bucket: bucket, Key: KEY_PREFIX + name }));
    return;
  }
  await fs.rm(path.join(localUploadDirectory, name), { force: true });
}
